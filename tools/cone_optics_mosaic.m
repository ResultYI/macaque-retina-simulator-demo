function [cm, evidence] = cone_optics_mosaic(data, pigment, macular, p, dt)
% Build the production capture mosaic with type-specific ISETBio OS attenuation.
assert(strcmp(p.cone_optics_revision,'isetbio_typed_OS_per_aperture_v2'), ...
    'ConeOptics:Revision','Explicit cone optical model revision required');
assert(strcmp(data.positionUnits,'microns') && all(ismember(data.types,[1 2 3])), ...
    'ConeOptics:Input','Micron coordinates and L/M/S types required');
ecc = sqrt(sum(data.positions.^2,2))/p.microns_per_degree;
[lengths, fovealLength] = cMosaic.outerSegmentLengthFromEccentricity(ecc);
relativeLength = lengths(:)/fovealLength;
assert(all(isfinite(relativeLength)) && all(relativeLength>0), ...
    'ConeOptics:Domain','Eccentricity outside the ISETBio OS data domain');
fovealLengths = PhotoreceptorDimensions({'FovealLCone','FovealMCone','FovealSCone'}, ...
    'OSlength','Human','CVRL');
fovealOD = pigment.opticalDensity(:);
specificDensity = fovealOD./fovealLengths;
types = data.types(:); factors = zeros(size(types));
% Match the fixed 400:10:700 nm support used by ISETBio's standard OS model.
attenuationPigment=cPhotoPigment('opticalDensity',pigment.opticalDensity);
for type = 1:3
    keep = types==type;
    if ~any(keep), continue; end
    absorbance = attenuationPigment.absorbance(:,type)';
    reference = -expm1(-log(10)*absorbance*fovealOD(type));
    valid = reference>0;
    % Keep ISETBio's wavelength-mean attenuation convention, using each type's spectrum/OD.
    localOD = specificDensity(type)*(fovealLengths(type)*relativeLength(keep));
    local = -expm1(-log(10)*localOD*absorbance(valid));
    factors(keep) = mean(local./reference(valid),2);
end
assert(all(isfinite(factors)) && all(factors>0), 'ConeOptics:OS','Invalid OS attenuation');
% Imported factors replace the built-in L-cone-only correction; they are not multiplied twice.
data.outerSegmentLengthAttenationFactors = factors;
cm = cMosaic('coneData',data,'pigment',pigment,'macular',macular,'wave',pigment.wave, ...
    'micronsPerDegree',p.microns_per_degree,'whichEye','right eye','integrationTime',dt, ...
    'noiseFlag','none','randomSeed',1,'useParfor',false, ...
    'eccVaryingConeAperture',true,'eccVaryingConeBlur',false, ...
    'eccVaryingOuterSegmentLength',true,'eccVaryingMacularPigmentDensity',true, ...
    'eccVaryingMacularPigmentDensityDynamic',false, ...
    'anchorAllEccVaryingParamsToTheirFovealValues',false, ...
    'rodIntrusionAdjustedConeAperture',false,'coneCouplingLambda',0, ...
    'coneApertureModifiers',struct('shape','Pillbox'));
assert(isequal(cm.coneApertureDiametersMicrons(:),data.lightGatheringApertureDiameters(:)), ...
    'ConeOptics:Diameter','Supplied frozen aperture diameters changed');
assert(isequal(cm.computeEffectiveOSlengthAttenuationFactors(1:numel(types))',factors), ...
    'ConeOptics:OS','Imported OS correction was not applied exactly once');
evidence = struct('revision',p.cone_optics_revision,'type_specific_diameter',false, ...
    'diameter_rule','Frozen full-support six-neighbour spacing times 0.79; no invented L/M/S diameter multiplier', ...
    'spatial_integration','Per-cone pillbox kernel at actual OI resolution; only exactly equal kernels share a compute group', ...
    'OS_rule','ISETBio Banks eccentricity fraction, wavelength-mean Beer-Lambert attenuation separately for each type', ...
    'OS_species','Human-borrowed optical model, not a macaque morphometric calibration', ...
    'foveal_OS_length_um_LMS',fovealLengths,'specific_density_per_um_LMS',specificDensity, ...
    'OS_length_um',fovealLengths(types).*relativeLength, ...
    'OS_attenuation',factors,'foveal_OD_preserved_LMS',fovealOD, ...
    'OS_attenuation_wave_nm',attenuationPigment.wave, ...
    'CVRL_length_role','Type-specific length baseline; specific density derived from the existing OD to avoid double-counting S-cone shortening', ...
    'spectral_limit','Wavelength-mean scalar attenuation follows the cMosaic approximation; not exact per-cone spectral self-screening');
end
