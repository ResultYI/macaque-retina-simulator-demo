class EccentricHCNative(LateralHCCandidate):
    """Reuse H1 native coefficients and the retained H2-only homotypic term."""
    def __init__(self, assembly):
        H1H2Native.__init__(self, assembly)
        self.calibration = MappingProxyType(dict(assembly.h1_calibration))
        self.tau_h_ms = float(self.calibration['tau_h_ms'])
        if not 10 <= self.tau_h_ms <= 40 or not self.calibration['metrics_sha256']:
            raise ContractError('H1 tau_h requires a bounded completed calibration decision')
        self.effective_h1_parameters = MappingProxyType(dict(SOURCE_VALUES,tau_h=self.tau_h_ms))
        self.coupling_rate = assembly.h2_coupling_rate
        self.Q = {'H1':csr(sparse.csr_matrix((len(self.h1_rows),len(self.h1_rows)))),
                  'H2':csr(assembly.h2_Q)}
        q = self.Q['H2'].tocoo()
        self.Qfull = csr(sparse.csr_matrix((q.data,(self.h2_rows[q.row],self.h2_rows[q.col])),
                                          shape=(self.nh,self.nh)))
        self.coupling_degree = self.Qfull.diagonal()
        self.coupling_neighbor = csr(sparse.diags(self.coupling_degree)-self.Qfull)
        self.identity.update(model=MODEL, H1_parameters=dict(self.effective_h1_parameters),
            calibration=dict(self.calibration),H1_explicit_lateral_coupling=False,
            retained_H2_Q=matrix_id(self.Q['H2']),retained_H2_coupling_rate=self.coupling_rate,
            implementation_sha256=digest(Path(__file__)))
        self.source_version = canonical_hash(self.identity)

    def _coefficients(self,y,t,anchor):
        a,b,outputs = super()._coefficients(y,t,anchor)
        # Retain the source lock used by the existing continuous-state transport.
        # Only H1's final coefficient pair changes; H2 and release coefficients do not.
        a,b = list(a),list(b)
        a[7],b[7] = a[7].copy(),b[7].copy()
        scale = SOURCE_VALUES['tau_h']/self.tau_h_ms
        a[7][self.h1_rows] *= scale
        b[7][self.h1_rows] *= scale
        return tuple(a),tuple(b),outputs


class EccentricHCAssembly:
    def __init__(self,parent,A,B,Q2,calibration,receipt,configuration):
        self.parent=parent;self._A=csr(A);self._B=csr(B)
        self.h1_calibration=dict(calibration)
        self.h2_Q=csr(Q2);self.h2_coupling_rate=receipt['H2_coupling_rate_per_second']
        self.h2_parameters=dict(parent.h2_parameters)
        self.layout=deepcopy(parent.layout)
        self.layout.update(model=MODEL,spatial_identity=receipt['spatial_identity'])
        self.connection_identity=dict(parent=parent.connection_identity,
            spatial_identity=receipt['spatial_identity'],A=matrix_id(A),B=matrix_id(B),
            H2_Q=matrix_id(Q2),normalization='complete fine rows before original-member projection')
        self.artifact_sha256=canonical_hash(dict(parent=parent.artifact_sha256,
            configuration=configuration,connections=self.connection_identity,calibration=calibration))
        self.operators=dict(A1=csr(A[parent.h1_rows]),A2=csr(A[parent.h2_rows]),
                            B1=csr(B[:,parent.h1_rows]),B2=csr(B[:,parent.h2_rows]))
        self.runtime_factories=dict(parent.runtime_factories,native=self.native_factory)
        self.native_boundary=None

    def __getattr__(self,name):
        return getattr(self.parent,name)

    def matrix(self,relative):
        if relative=='routes/cones_to_HC/mean_weights.npz': return self._A
        if relative=='routes/HC_to_cones/mean_weights.npz': return self._B
        if relative.startswith('h1_h2/') and Path(relative).stem in self.operators:
            return self.operators[Path(relative).stem]
        return self.parent.matrix(relative)

    def native_factory(self,assembly,*,torch=None,device=None,plans=None,bound=True):
        if torch is not None or device is not None or plans is not None:
            raise ContractError('Eccentric H1 currently requires the original CPU reference path')
        native=EccentricHCNative(assembly)
        if bound:
            if self.native_boundary is None: raise ContractError('New HC background has not been bound')
            native.boundary=self.native_boundary
        return native


def _initialize_inner(assembly,outer_seed,root,protocol):
    """Reuse the exact existing background algebra with new native dependencies."""
    parameters=canonical_hash(outer_seed['inner_parameters'])
    def binding(current,seed,unused_root,unused_protocol):
        if canonical_hash(seed['inner_parameters'])!=parameters:
            raise ContractError('HC background construction changed BC/AC/AII/RGC parameters')
        descriptor=dict(model=MODEL,artifact=current.artifact_sha256,parameters=parameters,
            states=canonical_hash(seed['states']),calibration=current.h1_calibration,
            boundary=seed['h1_h2_model']['boundary'])
        identity=canonical_hash(descriptor)
        current.parameter_binding_id=identity
        seed['h1_h2_model']['parameter_binding_id']=identity
        seed['hc_eccentric_binding']=dict(identity=identity,descriptor=descriptor)
        return SimpleNamespace(identity=identity,descriptor=descriptor)
    namespace=dict(initialize_joint_background.__globals__)
    namespace.update(H1H2Native=lambda a:a.runtime_factories['native'](a,bound=False),
                     bind_parameters=binding,MODEL=MODEL,
                     INITIALIZATION='HC_eccentric_new_background_existing_inner_parameters')
    initialize=FunctionType(initialize_joint_background.__code__,namespace,
        'initialize_eccentric_inner',initialize_joint_background.__defaults__,initialize_joint_background.__closure__)
    initialize.__kwdefaults__=dict(initialize_joint_background.__kwdefaults__ or {})
    return initialize(assembly,outer_seed,root,protocol)[0]


class EccentricConeHCModel:
    def __init__(self,repo_root,configuration=DEFAULT_CONFIGURATION):
        from .assembly import RetinaBuilder
        from tools.gin_hc2_bc1_context_support_v2 import protocol
        self.repo_root=Path(repo_root).resolve()
        self.configuration_path=checked_path(self.repo_root,configuration)
        cfg=json.loads(self.configuration_path.read_bytes());self.config=cfg
        if (cfg.get('schema')!='cone_hc_eccentric_research' or cfg.get('research_only') is not True
                or cfg.get('production_qualified') is not False or cfg.get('execution_mode')!='local_cpu'
                or cfg.get('background_mode')!='reuse_existing_HC_1000td_uniform_held_diagnostic'
                or cfg.get('H2_mode')!='retain_existing_A_B_parameters_and_homotypic_operator'
                or cfg.get('H1_explicit_lateral_coupling') is not False):
            raise ContractError('Explicit eccentric-H1, retained-H2 research configuration required')
        self.calibration=temporal_decision(self.repo_root,cfg['calibration'])
        directory=(self.repo_root/cfg['assets_directory']).resolve()
        receipt_path=checked_path(self.repo_root,directory/'SPATIAL_RECEIPT.json')
        receipt=json.loads(receipt_path.read_bytes());self.spatial_receipt=receipt
        if (receipt.get('status')!='PRECOMPUTED' or receipt.get('crop_renormalized') is not False
                or receipt.get('geometry_regenerated') is not False or receipt.get('calibration')!=self.calibration):
            raise ContractError('Completed matching eccentric HC precomputation required')
        for relative,expected in receipt['source_files'].items():
            checked_path(self.repo_root,relative,expected)
        for name,expected in receipt['output_files'].items():
            checked_path(self.repo_root,directory/name,expected)
        with np.load(directory/'MEMBERS.npz',allow_pickle=False) as z:
            self.members={k:z[k].copy() for k in z.files}
        with np.load(directory/'MASS_LEDGER.npz',allow_pickle=False) as z:
            self.mass={k:z[k].copy() for k in z.files}
        A,B,Q2=[sparse.load_npz(directory/(name+'.npz')).tocsr() for name in ('A_group','B_group','H2_Q')]
        bc=RetinaBuilder.build_research_bc(self.repo_root,cfg['bc_configuration'])
        parent,original=bc.assembly,bc.seed
        if parent.artifact_sha256!=receipt['source_assembly']:
            raise ContractError('Prepared operators belong to a different full-chain source assembly')
        for name,prefix in (('cones','cone'),('HC','hc')):
            population=parent.populations[name]
            for saved,actual in ((prefix+'_parent_rows',population.member_global_rows),
                    (prefix+'_group',population.fine_to_group[population.member_global_rows]),
                    (prefix+'_counts',population.counts)):
                if not np.array_equal(self.members[saved],actual):
                    raise ContractError('Prepared fine membership differs: '+saved)
        oldnative=parent.runtime_factories['native'](parent,bound=False)
        if (matrix_id(A)!=receipt['A_identity'] or matrix_id(B)!=receipt['B_identity']
                or matrix_id(Q2)!=receipt['H2_Q_identity']
                or np.max(abs((B-oldnative.B).data),initial=0.)>2e-14
                or np.max(abs((A[parent.h2_rows]-oldnative.A[parent.h2_rows]).data),initial=0.)>2e-14
                or matrix_id(Q2)!=matrix_id(oldnative.Q['H2'])
                or oldnative.coupling_rate!=receipt['H2_coupling_rate_per_second']
                or dict(oldnative.parameters)!=receipt['H2_parameters']):
            raise ContractError('H2 or original local feedback changed')
        self.assembly=EccentricHCAssembly(parent,A,B,Q2,self.calibration,receipt,cfg)
        self.A,self.B=self.assembly._A,self.assembly._B
        self.h1_rows,self.h2_rows=parent.h1_rows,parent.h2_rows
        self.input=json.loads(checked_path(self.repo_root,cfg['diagnostic_input_configuration']).read_bytes())['input']
        bg=float(self.input['background_td'])
        if bg!=1000.: raise ContractError('Existing HC diagnostic background changed')
        self.light=np.full(A.shape[1],bg)
        cone=cone_fixed_point(self.light);p=SOURCE_VALUES
        v=float(cone['Vis'][0]);adapt=(v/p['V_I'])**p['mu']
        h0=brentq(lambda h:h-p['g_t']*expit((v-h-p['V_k'])/p['V_n'])/adapt,0.,p['g_t']/adapt,xtol=1e-12)
        ah,bh=self.mass['A_group_held'],self.mass['B_group_held']
        if (not np.allclose(np.asarray(A.sum(1)).ravel()+ah,1.,rtol=0,atol=2e-14)
                or not np.allclose(np.asarray(B.sum(1)).ravel()+bh,self.mass['B_group_supported'],rtol=0,atol=2e-14)
                or np.any(ah<0) or np.any(bh<0)):
            raise ContractError('Explicit held/unsupported mass ledger differs')
        self.assembly.native_boundary=dict(A_release=ah*h0/p['g_t'],A_Vbar=ah*v,B_h=bh*h0)
        native=self.assembly.native_factory(self.assembly)
        initial=np.concatenate([cone[k] for k in ('X','C','Vis','g_i','Vbar')]+
            [np.full(len(self.h1_rows),h0),np.full(len(self.h1_rows),h0),np.full(A.shape[0],h0),
             np.full(len(native.aux_indices),h0)])
        self.start_anchor=AnalyticREAnchor(0.,self.light,self.light,self.light,1.,0)
        self.y0,self.background_diagnostics=native.equilibrate_native(initial,self.start_anchor,0.)
        self.background_rhs=float(np.max(abs(native.rhs(self.y0,0.,self.start_anchor))))
        if self.background_rhs>1e-8:
            raise ContractError('New eccentric HC background fails the existing 1e-8 native RHS gate')
        self.native=native
        seed=deepcopy(original);old_seed_identity=canonical_hash(original)
        seed.pop('lateral_hc_interface',None)
        seed['time_seconds']=0.
        for name in ('R','E'):seed['states']['cones','analytic_RE',name]=self.light.copy()
        for name in ('X','C','Vis','g_i','Vbar'):
            seed['states']['cones','reduced_native',name]=self.y0[native.slices[name]].copy()
        for name in ('w','z2'):
            seed['states']['HC',MECHANISM,name]=self.y0[native.slices[name]].copy()
        voltage=self.y0[native.slices['Vh']]
        for name,rows in (('h1',self.h1_rows),('h2',self.h2_rows)):
            seed['states']['HC',MECHANISM,name]=voltage[rows].copy()
        seed['states']['cones','selected_original_z1_auxiliary','z1_aux']=self.y0[native.slices['z1_aux']].copy()
        seed['input_reference']['native_background_td']=self.light.copy()
        seed['observation_prehistory'].update(history_times=np.array([0.]),history_values=voltage[None,:].copy(),
                                              prehistory=voltage.copy(),origin_seconds=0.)
        seed['h1_h2_model']=dict(model=MODEL,artifact=self.assembly.artifact_sha256,
            layout_sha256=canonical_hash(self.assembly.layout),parameters=dict(self.assembly.h2_parameters),
            boundary=deepcopy(self.assembly.native_boundary),H1_calibration=self.calibration,
            source_seed_sha256=old_seed_identity,qualification='CONDITIONAL_HELD_BACKGROUND',
            physiological_calibration=False,FIT_READY=False)
        self.protocol=protocol();self.protocol['start_seconds']=0.
        self.protocol['stop_seconds']=cfg['fullchain_duration_seconds']
        self.seed=_initialize_inner(self.assembly,seed,self.repo_root,self.protocol)
        if canonical_hash(self.seed['inner_parameters'])!=canonical_hash(original['inner_parameters']):
            raise ContractError('Existing BC/AC/AII/RGC physiological parameters changed')
        if canonical_hash(original)!=old_seed_identity:
            raise ContractError('Historical source seed was mutated')
        self.reference_bc_identity=bc.identity
        self.seed['hc_eccentric_binding'].update(reference_bc_identity=bc.identity,
            source_bc_parameter_binding=original['bc_physiology']['parameter_binding_id'])
        for frame in self.seed['native_inputs']:
            t=self.protocol['input_origin_seconds']+frame/self.protocol['input_fps']
            self.seed['native_inputs'][frame]=self.stimulus(t)
        self.identity=canonical_hash(dict(artifact=self.assembly.artifact_sha256,
            binding=self.seed['hc_eccentric_binding'],seed=self.seed,configuration=cfg,
            spatial_receipt_sha256=digest(receipt_path),native_identity=native.source_version))

    def stimulus(self,time_seconds,cone_types=None):
        """Mean the existing fine-member diagnostic, never a group-centroid mask."""
        if not self.input['onset_seconds']<=time_seconds<self.input['offset_seconds']:
            return self.light.copy()
        if cone_types is None:
            radius=np.linalg.norm(self.members['cone_IS_mm']-np.asarray(self.input['center_mm']),axis=1)
            selected=(radius>=self.input['inner_radius_mm'])&(radius<self.input['outer_radius_mm'])
        else:
            if not set(cone_types)<=set('LMS'): raise ContractError('Unknown diagnostic cone class')
            selected=np.isin(self.members['cone_types'],list(cone_types))
        fraction=np.bincount(self.members['cone_group'],weights=selected.astype(float),
                             minlength=len(self.light))/self.members['cone_counts']
        return self.light*(1+self.input['contrast']*fraction)

    def runner(self,protocol=None,*,execution_mode='local_cpu'):
        if execution_mode!='local_cpu': raise ContractError('Eccentric HC supports local_cpu only')
        return EccentricHCFullChainRunner(self.assembly,self.seed,self.protocol if protocol is None else protocol)


class EccentricHCFullChainRunner(H1H2GroupRunner):
    def __init__(self,assembly,seed,protocol,*,mode='reference',**kwargs):
        binding=seed.get('hc_eccentric_binding',{})
        if (mode!='reference' or kwargs.get('torch') is not None or kwargs.get('shared_plans') is not None
                or seed.get('h1_h2_model',{}).get('model')!=MODEL
                or seed['h1_h2_model'].get('artifact')!=assembly.artifact_sha256
                or binding.get('identity')!=getattr(assembly,'parameter_binding_id',None)
                or canonical_hash(seed['inner_parameters'])!=seed['joint_background_initialization']['parameters_sha256']):
            raise ContractError('New eccentric HC state and unchanged BC physiology binding required')
        GroupTimeArm.__init__(self,assembly,seed,protocol,mode=mode,**kwargs)
        self.identity=canonical_hash(dict(parent_execution=self.identity,eccentric_binding=binding,
            native_identity=self.native_physics.source_version,H1_tau_h_ms=self.native_physics.tau_h_ms))

    def checkpoint_payload(self,**kwargs):
        payload=GroupTimeArm.checkpoint_payload(self,**kwargs)
        payload['controller']['hc_eccentric_binding']=self.seed['hc_eccentric_binding']
        payload['controller']['H1_tau_h_ms']=self.native_physics.tau_h_ms
        payload['controller']['BC_parameter_hash']=canonical_hash(self.seed['inner_parameters'])
        return payload

    @classmethod
    def from_checkpoint(cls,assembly,seed,protocol,payload,**kwargs):
        c=payload.get('controller',{})
        if (canonical_hash(c.get('hc_eccentric_binding'))!=canonical_hash(seed.get('hc_eccentric_binding'))
                or c.get('H1_tau_h_ms')!=assembly.h1_calibration['tau_h_ms']
                or c.get('BC_parameter_hash')!=canonical_hash(seed['inner_parameters'])):
            raise ContractError('Checkpoint A, tau_h, state or BC binding differs; rebuild background')
        return GroupTimeArm.from_checkpoint.__func__(cls,assembly,seed,protocol,payload,**kwargs)
