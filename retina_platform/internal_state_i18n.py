_PATTERN = re.compile('|'.join(re.escape(key) for key in sorted(_MESSAGES, key=len, reverse=True)))


def translate(text, language='zh'):
    """Translate display text once, including fragments around saved numeric data."""
    text = str(text)
    if language == 'zh':
        return text
    if language not in ('ja', 'en'):
        raise ValueError('Unsupported display language: ' + str(language))
    column = 0 if language == 'ja' else 1
    return _PATTERN.sub(lambda match: _MESSAGES[match.group(0)][column], text)
